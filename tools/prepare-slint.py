#!/usr/bin/env python3
"""Prepare the pinned official Slint source before Cargo resolves dependencies."""
import argparse
import fcntl
import hashlib
import json
import os
from pathlib import Path
import shlex
import subprocess
import tempfile
import tomllib


def git(directory, *args):
    result = subprocess.run(
        ["git", "-C", str(directory), *args], capture_output=True, text=True,
    )
    if result.returncode:
        raise RuntimeError(f"git {' '.join(args)} failed: {result.stderr.strip()}")
    return result.stdout.strip()


def verify(source, spec):
    if git(source, "rev-parse", "HEAD") != spec["upstream"]["commit"]:
        raise RuntimeError("Prepared Slint has a different upstream commit; preserved without changes")
    if git(source, "write-tree") != spec["patched_tree"]:
        raise RuntimeError("Prepared Slint index differs from the pinned patched tree; preserved without changes")
    if git(source, "diff", "--name-only") or git(source, "ls-files", "--others", "--exclude-standard"):
        raise RuntimeError("Prepared Slint contains local changes; preserved without changes")
    for name, path in spec["packages"].items():
        directory = (source / path).resolve()
        if not directory.is_relative_to(source.resolve()):
            raise RuntimeError(f"Package path escapes the prepared source: {name}")
        data = tomllib.loads((directory / "Cargo.toml").read_text())
        if data["package"]["name"] != name:
            raise RuntimeError(f"Package name mismatch: {name}")


def prepare(root, offline=False):
    bundle = root / "patches/slint"
    spec = json.loads((bundle / "manifest.json").read_text())
    patch = bundle / spec["patch"]
    if hashlib.sha256(patch.read_bytes()).hexdigest() != spec["patch_sha256"]:
        raise RuntimeError("Slint patch checksum mismatch")
    cache = root / ".slint"
    cache.mkdir(exist_ok=True)
    source = cache / "source"
    # Serialize publication and verification across concurrent preparation runs.
    with (cache / "prepare.lock").open("a") as lock:
        fcntl.flock(lock, fcntl.LOCK_EX)
        if source.exists():
            verify(source, spec)
        else:
            if offline:
                raise RuntimeError("No prepared Slint source; run tools/prepare-slint.py online first")
            with tempfile.TemporaryDirectory(prefix="prepare-", dir=cache) as staging:
                checkout = Path(staging) / "source"
                checkout.mkdir()
                git(checkout, "init", "--quiet")
                git(checkout, "fetch", "--depth=1", spec["upstream"]["url"], spec["upstream"]["commit"])
                git(checkout, "checkout", "--quiet", "--detach", "FETCH_HEAD")
                if git(checkout, "rev-parse", "HEAD^{tree}") != spec["upstream"]["tree"]:
                    raise RuntimeError("Official Slint source tree mismatch")
                git(checkout, "apply", "--check", str(patch.resolve()))
                git(checkout, "apply", "--index", str(patch.resolve()))
                verify(checkout, spec)
                checkout.rename(source)
        # Absolute paths allow --config from an unrelated application's workspace.
        lines = ["# Generated by tools/prepare-slint.py; do not commit machine-local paths.",
                 "[patch.crates-io]"]
        lines.extend(f'{name} = {{ path = {json.dumps(str((source / path).resolve()))} }}'
                     for name, path in spec["packages"].items())
        config = cache / "cargo-patch.toml"
        with tempfile.NamedTemporaryFile(mode="w", dir=cache, delete=False) as temporary:
            temporary.write("\n".join(lines) + "\n")
        os.replace(temporary.name, config)
    return config


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--offline", action="store_true", help="verify and reuse existing source without fetching")
    args = parser.parse_args()
    try:
        config = prepare(Path(__file__).resolve().parents[1], args.offline)
    except (OSError, RuntimeError, ValueError) as error:
        parser.exit(1, f"Slint preparation failed: {error}\n")
    print("Verified official Slint 1.18.1 with the repository patch set.")
    print(f"External workspace: cargo --config {shlex.quote(str(config))} <command>")


if __name__ == "__main__":
    main()
